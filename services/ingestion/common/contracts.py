"""Versioned ingestion service contracts (v1).

These Pydantic models are the wire format for every provider adapter
(``GET /health``, ``GET /v1/capabilities``, ``POST /v1/search``,
``POST /v1/fetch``). JSON Schema snapshots live in
``contracts/ingestion/v1/`` and are generated by ``gen_schemas.py``; the
``test_contracts_match`` test fails if they drift.
"""

from typing import Any, Literal

from pydantic import BaseModel, Field

ArtifactType = Literal["lyrics", "chord_chart", "tablature", "sheet_music"]


class HealthResponse(BaseModel):
    status: Literal["ok"] = "ok"
    service: str
    version: str


class CapabilityResponse(BaseModel):
    provider: str
    version: str = "v1"
    artifact_types: list[ArtifactType]
    supports_search: bool = True
    supports_fetch: bool = True
    allows_storage: bool = False
    storage_note: str = ""
    rate_limit_requests: int = 0
    rate_limit_period_seconds: float = 60.0


class SearchRequest(BaseModel):
    query: str = Field(min_length=1, max_length=200)
    artifact_types: list[ArtifactType] = Field(default_factory=list)
    limit: int = Field(default=10, ge=1, le=50)


class SearchItem(BaseModel):
    provider: str
    external_id: str
    title: str | None = None
    artist: str | None = None
    artifact_types: list[ArtifactType] = Field(default_factory=list)
    source_url: str | None = None
    attribution: str | None = None
    confidence: float | None = Field(default=None, ge=0.0, le=1.0)
    warnings: list[str] = Field(default_factory=list)


class SearchResponse(BaseModel):
    items: list[SearchItem] = Field(default_factory=list)
    provider: str = ""


class FetchRequest(BaseModel):
    external_id: str = Field(min_length=1, max_length=512)
    artifact_types: list[ArtifactType] = Field(default_factory=list)


class FetchedArtifact(BaseModel):
    artifact_type: ArtifactType
    mime_type: str
    content_text: str | None = None
    content_base64: str | None = None
    attribution: str | None = None
    storage_allowed: bool = False
    warnings: list[str] = Field(default_factory=list)


class FetchResponse(BaseModel):
    provider: str = ""
    external_id: str = ""
    title: str | None = None
    artist: str | None = None
    source_url: str | None = None
    artifacts: list[FetchedArtifact] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


class ErrorDetail(BaseModel):
    code: str
    message: str
    retryable: bool = False
    retry_after_seconds: float | None = None


class ErrorEnvelope(BaseModel):
    error: ErrorDetail


class StatsResponse(BaseModel):
    provider: str = ""
    limiter: dict[str, Any] = Field(default_factory=dict)
    cache: dict[str, Any] = Field(default_factory=dict)
    upstream_requests: int = 0
    throttled_requests: int = 0


CONTRACT_MODELS: dict[str, type[BaseModel]] = {
    "health": HealthResponse,
    "capabilities": CapabilityResponse,
    "search_request": SearchRequest,
    "search_response": SearchResponse,
    "fetch_request": FetchRequest,
    "fetch_response": FetchResponse,
    "error": ErrorEnvelope,
    "stats": StatsResponse,
}
